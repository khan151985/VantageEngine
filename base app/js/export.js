    // Actually start media playback (called after fullscreen prompt or directly)
    startMediaPlayback(overlay, video, skipBtn, skipText, unmuteBtn, settings, mediaSrc, isImage, selectedLang = null) {
        // Show media overlay
        overlay.style.display = 'flex';
        
        // Set skip button text
        const defaultText = isImage ? 'Enter Experience' : 'Skip Intro';
        if (skipText) {
            skipText.textContent = settings.skipButton.text || defaultText;
        }
        
        // Handle skip/continue function
        const handleSkip = () => {
            overlay.style.opacity = '0';
            overlay.style.transition = 'opacity 0.5s ease';
            setTimeout(() => {
                overlay.style.display = 'none';
                if (video) video.pause();
                
                // Apply selected language if language selection was used
                if (selectedLang) {
                    this.applySelectedLanguage(selectedLang);
                }
                
                this.showMainApp();
            }, 500);
        };
        skipBtn.addEventListener('click', handleSkip);
        
        // Show skip button after delay
        const skipDelay = (settings.skipButton.showAfter || 2) * 1000;
        setTimeout(() => {
            if (skipBtn) skipBtn.style.display = 'flex';
        }, skipDelay);
        
        if (isImage) {
            // IMAGE MODE
            // Hide video element, create/show image
            if (video) video.style.display = 'none';
            
            const img = document.createElement('img');
            img.src = mediaSrc;
            img.style.cssText = 'width: 100%; height: 100%; object-fit: cover;';
            overlay.insertBefore(img, overlay.firstChild);
            
            // Hide unmute button for images
            if (unmuteBtn) unmuteBtn.style.display = 'none';
            
            // Auto-advance for images if enabled
            if (settings.autoAdvance.enabled) {
                const autoDelay = (settings.autoAdvance.delay || 5) * 1000;
                setTimeout(() => {
                    handleSkip();
                }, autoDelay);
            }
            
        } else {
            // VIDEO MODE
            if (!video) {
                this.showMainApp();
                return;
            }
            
            video.style.display = 'block';
            video.src = mediaSrc;
            video.muted = false; // Try with sound first
            
            // Handle unmute button (shown if autoplay with sound is blocked)
            const handleUnmute = () => {
                video.muted = false;
                video.play().catch(() => {});
                if (unmuteBtn) unmuteBtn.style.display = 'none';
            };
            unmuteBtn.addEventListener('click', handleUnmute);
            
            // Also unmute on any touch/click on video
            video.addEventListener('click', handleUnmute, { once: true });
            
            // Handle video end
            video.addEventListener('ended', () => {
                handleSkip();
            });
            
            // Handle video error
            video.addEventListener('error', () => {
                console.error('Startup video failed to load');
                overlay.style.display = 'none';
                this.showMainApp();
            });
            
            // Start playing - try with sound first
            video.play().then(() => {
                // Autoplay with sound worked!
                console.log('Video playing with sound');
            }).catch(err => {
                console.log('Video autoplay with sound blocked, trying muted:', err);
                // Try muted autoplay
                video.muted = true;
                video.play().then(() => {
                    // Muted autoplay worked - show unmute button
                    if (unmuteBtn) {
                        unmuteBtn.style.display = 'block';
                        unmuteBtn.textContent = '🔊 Tap for sound';
                    }
                }).catch(err2 => {
                    console.log('Even muted autoplay blocked:', err2);
                    // Show a play button if even muted autoplay is blocked
                    const playBtn = document.createElement('button');
                    playBtn.textContent = '▶ Play Intro';
                    playBtn.className = 'startup-video-skip';
                    playBtn.style.cssText = 'display: flex; bottom: 50%; right: 50%; transform: translate(50%, 50%);';
                    overlay.appendChild(playBtn);
                    playBtn.addEventListener('click', () => {
                        video.muted = false;
                        video.play();
                        playBtn.remove();
                    });
                });
            });
        }
    },
    
