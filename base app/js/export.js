    // Helper: Base64 to binary
    base64ToBinary(base64) {
        const binary = atob(base64);
        const len = binary.length;
        const bytes = new Uint8Array(len);
        for (let i = 0; i < len; i++) {
            bytes[i] = binary.charCodeAt(i);
        }
        return bytes;
    },

    // Helper: Get extension from MIME
    getExtensionFromMime(dataUrl) {
        if (!dataUrl) return 'bin';
        const match = dataUrl.match(/^data:([^;]+)/);
        if (!match) return 'bin';

        const mime = match[1];
        const mimeMap = {
            'image/jpeg': 'jpg',
            'image/png': 'png',
            'image/webp': 'webp',
            'video/mp4': 'mp4',
            'video/webm': 'webm',
            'audio/mpeg': 'mp3',
            'audio/wav': 'wav',
            'audio/ogg': 'ogg'
        };

        return mimeMap[mime] || 'bin';
    },

