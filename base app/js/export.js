    // Filter search dropdown based on query - sorted by match position priority
    filterSearchDropdown(query) {
        const container = document.getElementById('search-dropdown');
        if (!container) return;
        
        const lowerQuery = query.toLowerCase();
        // Also create simplified query (without diacritics) for matching
        const simpleQuery = this.removeDiacritics(lowerQuery);
        
        // Get all points with their localized names and match positions
        const matchedPoints = this.points
            .map(point => {
                const displayName = (point.names && point.names[this.currentLanguage]) || point.name || 'Point';
                const lowerName = displayName.toLowerCase();
                // Create simplified version of name for matching
                const simpleName = this.removeDiacritics(lowerName);
                
                // Check for match in original name OR simplified name
                let matchPos = lowerName.indexOf(lowerQuery);
                if (matchPos === -1) {
                    // Try matching simplified query against simplified name
                    matchPos = simpleName.indexOf(simpleQuery);
                }
                
                return {
                    ...point,
                    displayName,
                    matchPos
                };
            })
            .filter(p => p.matchPos !== -1) // Only keep matches
            .sort((a, b) => {
                // First by match position (earlier = higher priority)
                if (a.matchPos !== b.matchPos) return a.matchPos - b.matchPos;
                // Then alphabetically
                return a.displayName.toLowerCase().localeCompare(b.displayName.toLowerCase());
            });
        
        // Rebuild the search items HTML
        const searchItemsContainer = container.querySelector('.search-items');
        if (!searchItemsContainer) return;
        
        if (matchedPoints.length === 0) {
            searchItemsContainer.innerHTML = '<div class="search-no-results">No points found</div>';
        } else {
            let html = '';
            matchedPoints.forEach(point => {
                const color = point.style.color || '#00C8FF';
                const iconType = point.style.iconType || 'default';
                const customIcon = point.style.customIcon;
                
                html += '<div class="search-item" data-point-id="' + point.id + '">';
                
                // Show custom icon if available, otherwise colored dot
                if (iconType === 'custom' && customIcon) {
                    html += '<img class="search-item-icon-img" src="' + customIcon + '" alt="" style="width: 24px; height: 24px; object-fit: contain; border-radius: 4px;">';
                } else {
                    html += '<div class="search-item-icon" style="background:' + color + '"></div>';
                }
                
                html += '<span>' + point.displayName + '</span>';
                html += '</div>';
            });
            searchItemsContainer.innerHTML = html;
        }
        
        // Re-attach click handlers
        this.attachSearchItemHandlers();
    },
    
