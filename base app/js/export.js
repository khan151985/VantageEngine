    playSound(soundType) {
        if (!this.soundsEnabled || !this.audioContext) return;
        
        const soundId = this.soundAssignments[soundType];
        if (!soundId || soundId === 'none') return;
        
        const soundDefs = {
            click1: { freq: 800, duration: 0.05, type: 'sine' },
            click2: { freq: 600, duration: 0.08, type: 'square' },
            pop: { freq: 400, duration: 0.1, type: 'sine', bend: 600 },
            whoosh: { freq: 200, duration: 0.15, type: 'sawtooth', bend: 800 },
            chime: { freq: 880, duration: 0.2, type: 'sine' },
            subtle: { freq: 300, duration: 0.05, type: 'sine' }
        };
        
        const def = soundDefs[soundId];
        if (!def) return;
        
        try {
            const oscillator = this.audioContext.createOscillator();
            const gainNode = this.audioContext.createGain();
            
            oscillator.type = def.type;
            oscillator.frequency.setValueAtTime(def.freq, this.audioContext.currentTime);
            
            if (def.bend) {
                oscillator.frequency.linearRampToValueAtTime(
                    def.bend, 
                    this.audioContext.currentTime + def.duration
                );
            }
            
            gainNode.gain.setValueAtTime(this.soundVolume * 0.3, this.audioContext.currentTime);
            gainNode.gain.exponentialRampToValueAtTime(
                0.01, 
                this.audioContext.currentTime + def.duration
            );
            
            oscillator.connect(gainNode);
            gainNode.connect(this.audioContext.destination);
            
            oscillator.start();
            oscillator.stop(this.audioContext.currentTime + def.duration);
        } catch (e) {
            console.warn('Sound playback error:', e);
        }
    },
    
