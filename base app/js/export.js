    // Shared ZIP generator
    async generateProjectZip(project, onProgress) {
        const zip = new JSZip();

        onProgress(0, 'Preparing project data...');

        // Create folder structure
        const jsFolder = zip.folder('js');
        const cssFolder = zip.folder('css');
        const assetsFolder = zip.folder('assets');
        const modelsFolder = assetsFolder.folder('models');
        const mediaFolder = assetsFolder.folder('media');
        const dataFolder = zip.folder('data');

        onProgress(10, 'Generating HTML...');

        // Generate index.html
        const html = this.generateHTML(project);
        zip.file('index.html', html);

        onProgress(20, 'Bundling styles...');

        // Generate CSS
        const css = this.generateCSS(project);
        cssFolder.file('styles.css', css);

        onProgress(30, 'Bundling scripts...');

        // Generate JS
        const exportData = this.prepareExportData(project);
        const js = this.generateJS(project, exportData);
        jsFolder.file('viewer.js', js);

        onProgress(40, 'Processing 3D models...');

        // Export models from stored file data
        let missingModels = [];
        console.log('Exporting', project.meshes.length, 'meshes...');

        for (let i = 0; i < project.meshes.length; i++) {
            const mesh = project.meshes[i];
            console.log('Processing mesh:', mesh.name, 'hasFileData:', !!mesh.fileData, 'fileDataLength:', mesh.fileData ? mesh.fileData.length : 0);

            if (mesh.fileData) {
                try {
                    // Extract base64 data (remove data URL prefix if present)
                    const base64Data = mesh.fileData.split(',')[1] || mesh.fileData;
                    const binary = this.base64ToBinary(base64Data);
                    const uniqueFilename = `${mesh.id}_${mesh.filename}`;
                    modelsFolder.file(uniqueFilename, binary);
                    console.log('✓ Added model to export:', uniqueFilename, 'size:', binary.length, 'bytes');
                } catch (err) {
                    console.error('✗ Failed to export model:', mesh.filename, err);
                    missingModels.push(mesh.name);
                }
            } else {
                console.warn('⚠ WARNING: Model "' + mesh.name + '" has no fileData!');
                missingModels.push(mesh.name);
            }
            onProgress(40 + (i / Math.max(project.meshes.length, 1)) * 20, `Processing model: ${mesh.name}`);
        }

        // Show alert if models are missing
        if (missingModels.length > 0) {
            alert('WARNING: The following models have no data and will NOT appear in the export:\\n\\n' +
                missingModels.join('\\n') +
                '\\n\\nTo fix: Delete these meshes and re-import them from the original .glb files.');
        }

        onProgress(60, 'Processing media...');

        // Export media
        for (let i = 0; i < project.media.length; i++) {
            const media = project.media[i];
            if (media.data) {
                const base64Data = media.data.split(',')[1] || media.data;
                const binary = this.base64ToBinary(base64Data);
                const ext = this.getExtensionFromMime(media.data) || 'bin';
                mediaFolder.file(`${media.id}.${ext}`, binary);
            }
            onProgress(60 + (i / Math.max(project.media.length, 1)) * 10, `Processing media: ${media.name}`);
        }

        // Export cover image if set
        if (project.settings.coverImage) {
            const base64Data = project.settings.coverImage.split(',')[1] || project.settings.coverImage;
            const binary = this.base64ToBinary(base64Data);
            assetsFolder.file('cover.jpg', binary);
        }

        // Export point marker mesh if set
        if (project.settings.pointMarkerMesh && project.settings.pointMarkerMesh.data) {
            try {
                const marker = project.settings.pointMarkerMesh;
                const base64Data = marker.data.split(',')[1] || marker.data;
                const binary = this.base64ToBinary(base64Data);
                modelsFolder.file(marker.filename || 'marker.glb', binary);
                console.log('Added point marker mesh to export');
            } catch (err) {
                console.error('Failed to export point marker mesh:', err);
            }
        }

        onProgress(70, 'Generating data files...');

        // Generate data files
        dataFolder.file('config.json', JSON.stringify(exportData.config, null, 2));
        dataFolder.file('points.json', JSON.stringify(exportData.points, null, 2));
        dataFolder.file('textboxes.json', JSON.stringify(exportData.textboxes, null, 2));
        dataFolder.file('pathAnimations.json', JSON.stringify(exportData.pathAnimations || [], null, 2));

        onProgress(80, 'Adding documentation...');

        // Add README
        zip.file('README.txt', this.generateReadme(project));

        onProgress(90, 'Finalizing...');

        return zip;
    },


