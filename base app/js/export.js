    // Toggle mesh visibility based on trigger type (category, point, actionButton)
    toggleMeshesForTrigger(triggerType, targetId, isActive) {
        if (!this.meshObjects) return;
        
        // Handle new visibilityMeshes array approach (for points and categories)
        if (triggerType === 'point') {
            const point = this.points.find(p => p.id === targetId);
            if (point.visibilityMeshes && point.visibilityMeshes.length > 0) {
                point.visibilityMeshes.forEach(meshId => {
                    const meshObj = this.meshObjects.get(meshId);
                    if (meshObj) {
                        meshObj.visible = isActive;
                        console.log('Point mesh visibility:', meshId, isActive);
                    }
                });
            }
        } else if (triggerType === 'category') {
            const category = this.config.categories.find(c => c.id === targetId);
            if (category.visibilityMeshes && category.visibilityMeshes.length > 0) {
                category.visibilityMeshes.forEach(meshId => {
                    const meshObj = this.meshObjects.get(meshId);
                    if (meshObj) {
                        meshObj.visible = isActive;
                        console.log('Category mesh visibility:', meshId, isActive);
                    }
                });
            }
        }
        
        // Also handle legacy single-mesh visibility trigger on meshes
        this.config.meshes.forEach(meshConfig => {
            const trigger = meshConfig.visibilityTrigger;
            if (!trigger || trigger.type !== triggerType || trigger.targetId !== targetId) return;
            
            const meshObj = this.meshObjects.get(meshConfig.id);
            if (!meshObj) return;
            
            // Determine visibility based on mode
            const mode = trigger.mode || 'show';
            let shouldShow;
            
            if (mode === 'show') {
                shouldShow = isActive;
            } else if (mode === 'hide') {
                shouldShow = !isActive;
            } else if (mode === 'toggle') {
                shouldShow = !meshObj.visible;
            }
            
            meshObj.visible = shouldShow;
            console.log('Mesh visibility:', meshConfig.name, shouldShow);
        });
    },
    
