    // Get position along linear path
    getLinearPathPosition(points, progress, isLooping) {
        if (points.length < 2) return { position: points[0].clone() || new THREE.Vector3(), tangent: new THREE.Vector3(0, 0, 1) };
        
        // Calculate total length
        let totalLength = 0;
        const segments = [];
        for (let i = 1; i < points.length; i++) {
            const len = points[i].distanceTo(points[i-1]);
            segments.push({ start: points[i-1], end: points[i], length: len });
            totalLength += len;
        }
        
        if (isLooping) {
            const len = points[0].distanceTo(points[points.length - 1]);
            segments.push({ start: points[points.length - 1], end: points[0], length: len });
            totalLength += len;
        }
        
        // Find position along path
        const targetDist = progress * totalLength;
        let accumulated = 0;
        
        for (const seg of segments) {
            if (accumulated + seg.length >= targetDist) {
                const t = (targetDist - accumulated) / seg.length;
                const position = seg.start.clone().lerp(seg.end, t);
                const tangent = seg.end.clone().sub(seg.start).normalize();
                return { position, tangent };
            }
            accumulated += seg.length;
        }
        
        // Return last point
        return { 
            position: points[points.length - 1].clone(), 
            tangent: points.length >= 2 ? points[points.length - 1].clone().sub(points[points.length - 2]).normalize() : new THREE.Vector3(0, 0, 1)
        };
    },
    
