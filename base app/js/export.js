    // Recenter camera to start view or default
    recenterCamera() {
        // Block if camera is locked (check both buttons)
        const lockBtn = document.getElementById('btn-camera-lock');
        const lockBtnMobile = document.getElementById('btn-camera-lock-mobile');
        if ((lockBtn && lockBtn.classList.contains('locked')) || 
            (lockBtnMobile && lockBtnMobile.classList.contains('locked'))) {
            console.log('Camera locked - recenter blocked');
            return;
        }
        
        // Detect if mobile device
        const isMobile = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent) || window.innerWidth <= 768;
        
        // Get the appropriate view based on device
        let view;
        if (isMobile) {
            // Try mobile view first, fall back to desktop
            view = this.config.settings.defaultViewMobile || 
                   this.config.startView || 
                   this.config.defaultView || 
                   this.config.settings.defaultView;
        } else {
            // Desktop view
            view = this.config.startView || this.config.defaultView || this.config.settings.defaultView;
        }

        if (view) {
            // Use user-defined start view
            
            // Check if we have valid position/target
            if (view.position && view.target) {
                // Animate to view
                const duration = 1000;
                const startPos = this.camera.position.clone();
                const startTarget = this.controls.target.clone();
                const endPos = new THREE.Vector3(view.position.x, view.position.y, view.position.z);
                const endTarget = new THREE.Vector3(view.target.x, view.target.y, view.target.z);
                
                const startTime = Date.now();
                
                const animateReset = () => {
                    const now = Date.now();
                    const progress = Math.min((now - startTime) / duration, 1);
                    const ease = 1 - Math.pow(1 - progress, 3); // Cubic ease out
                    
                    this.camera.position.lerpVectors(startPos, endPos, ease);
                    this.controls.target.lerpVectors(startTarget, endTarget, ease);
                    this.controls.update();
                    
                    if (progress < 1) {
                        requestAnimationFrame(animateReset);
                    }
                };
                
                animateReset();
                return;
            }
        }
        
        // Fallback to controls reset
        this.controls.reset();
    },
    
