    // Setup draggable control button for mobile
    setupDraggableControlButton() {
        const btn = document.getElementById('btn-control-mode');
        if (!btn) return;
        
        // Only enable on mobile/touch devices
        const isMobile = window.innerWidth <= 900 || 'ontouchstart' in window;
        if (!isMobile) return;
        
        let isDragging = false;
        let hasMoved = false;
        let startX, startY, startLeft, startTop;
        let currentX, currentY;
        let animationFrame = null;
        
        // Cache viewport dimensions
        const viewportWidth = window.innerWidth;
        const viewportHeight = window.innerHeight;
        const btnSize = 44;
        
        // Load saved position from localStorage
        const savedPos = localStorage.getItem('controlBtnPos');
        if (savedPos) {
            try {
                const pos = JSON.parse(savedPos);
                btn.style.position = 'fixed';
                btn.style.left = pos.left + 'px';
                btn.style.top = pos.top + 'px';
                btn.style.right = 'auto';
                btn.style.transform = 'none';
                btn.style.zIndex = '999999';
            } catch(e) {}
        }
        
        const updatePosition = () => {
            if (!isDragging) return;
            
            // Keep within canvas area (not behind toolbars)
            // Top: below both toolbars (~140px), Bottom: above menu (~70px)
            const topBoundary = 140;
            const bottomBoundary = viewportHeight - 70 - btnSize;
            
            const newLeft = Math.max(10, Math.min(viewportWidth - btnSize - 10, currentX));
            const newTop = Math.max(topBoundary, Math.min(bottomBoundary, currentY));
            
            btn.style.left = newLeft + 'px';
            btn.style.top = newTop + 'px';
            
            animationFrame = null;
        };
        
        const onStart = (e) => {
            const touch = e.touches ? e.touches[0] : e;
            startX = touch.clientX;
            startY = touch.clientY;
            
            const rect = btn.getBoundingClientRect();
            startLeft = rect.left;
            startTop = rect.top;
            
            isDragging = true;
            hasMoved = false;
            
            // Prepare for smooth movement
            btn.style.right = 'auto';
            btn.style.transform = 'none';
            btn.style.zIndex = '999999';
            btn.classList.add('dragging');
        };
        
        const onMove = (e) => {
            if (!isDragging) return;
            
            // Prevent scrolling while dragging
            if (e.cancelable) e.preventDefault();
            
            const touch = e.touches ? e.touches[0] : e;
            const deltaX = touch.clientX - startX;
            const deltaY = touch.clientY - startY;
            
            // Only consider it a drag if moved more than 5px
            if (Math.abs(deltaX) > 5 || Math.abs(deltaY) > 5) {
                hasMoved = true;
            }
            
            currentX = startLeft + deltaX;
            currentY = startTop + deltaY;
            
            // Use requestAnimationFrame for smooth updates
            if (!animationFrame) {
                animationFrame = requestAnimationFrame(updatePosition);
            }
        };
        
        const onEnd = (e) => {
            if (!isDragging) return;
            isDragging = false;
            btn.classList.remove('dragging');
            
            if (animationFrame) {
                cancelAnimationFrame(animationFrame);
                animationFrame = null;
            }
            
            // Save position to localStorage
            const rect = btn.getBoundingClientRect();
            localStorage.setItem('controlBtnPos', JSON.stringify({
                left: rect.left,
                top: rect.top
            }));
            
            // If dragged, prevent the click from toggling mode
            if (hasMoved) {
                e.preventDefault();
                e.stopPropagation();
            }
        };
        
        // Touch events
        btn.addEventListener('touchstart', onStart, { passive: true });
        btn.addEventListener('touchmove', onMove, { passive: false });
        btn.addEventListener('touchend', onEnd, { passive: false });
        
        // Mouse events (for testing on desktop)
        btn.addEventListener('mousedown', onStart);
        document.addEventListener('mousemove', onMove);
        document.addEventListener('mouseup', onEnd);
    },
    
