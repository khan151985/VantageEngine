    // Create path curve from points
    createPathCurve(path) {
        if (!path.points || path.points.length < 2) return null;
        
        const positions = path.points.map(p => 
            new THREE.Vector3(p.position.x, p.position.y, p.position.z)
        );
        
        if (path.pathType === 'linear') {
            // For linear, we'll handle interpolation manually
            return { type: 'linear', points: positions, isLooping: path.isLooping };
        }
        
        // Bezier/Catmull-Rom
        let curvePoints = [...positions];
        if (path.isLooping && curvePoints.length >= 3) {
            curvePoints.push(curvePoints[0].clone());
        }
        
        const curve = new THREE.CatmullRomCurve3(curvePoints, path.isLooping, 'catmullrom', path.curveTension || 0.5);
        curve.type = 'bezier';
        curve.isLooping = path.isLooping;
        return curve;
    },
    
